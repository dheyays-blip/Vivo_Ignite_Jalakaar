def normalise_phone(raw: str) -> str:
    """Indian mobile -> E.164. Must stay in lockstep with validatePhone in
    web/script.js — if they disagree, a number that passes in the browser
    fails at the API, which is a miserable bug to chase.

    Strip the country code by LENGTH, never by prefix. `91` is a real Indian
    mobile prefix as well as the country code, so the obvious
    `re.sub(r"^(0?91|0)", "", digits)` turns a valid 9123456780 into an
    8-digit string and rejects it. Only remove 91 when what remains is
    still a full 10-digit number.
    """
    digits = re.sub(r"\D", "", raw or "")

    if len(digits) == 13 and digits.startswith("091"):
        local = digits[3:]
    elif len(digits) == 12 and digits.startswith("91"):
        local = digits[2:]
    elif len(digits) == 11 and digits.startswith("0"):
        local = digits[1:]
    else:
        local = digits

    if len(local) != 10 or not re.match(r"^[6-9]", local):
        raise ValueError("Enter a 10-digit Indian mobile number.")
    return f"+91{local}"
